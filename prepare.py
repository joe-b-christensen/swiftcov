#!/usr/bin/env python3
"""SwiftCov: one-time setup for evaluate.py.

    python3 prepare.py            # build the reference, prepare datasets, record expected outputs + timings

Steps:
  1. Build the reference: bedtools v2.31.1 (commit 705ccfd) from GitHub with its release flags (-O2), linked against
     zlib v1.3.1, which is also built from GitHub source. The optional bzip2/LZMA CRAM codecs are left out of both
     the reference and SwiftCov.
  2. Prepare the benchmark and holdout BED files: real data rebuilt from the compact streams in data/ (each checked
     against its row count, byte count and sha256 in data/curation.json) and synthetic sets generated by gen_data.py
     (fixed seeds).
  3. Run the reference on each dataset in its benchmark mode and in -sorted mode; record sha256 of the output, its
     size and the wall times (best of 3 below 5 s).
  4. Write bench/manifest.json (expected outputs, timings, environment, script and data hashes).
Re-running is safe: finished steps are skipped.

bedtools' default mode holds every read in memory: 4.5 GiB for the 12.5 million chr21 reads.
"""
import hashlib
import json
import os
import pathlib
import platform
import subprocess
import time

import gen_data

ROOT = pathlib.Path(__file__).resolve().parent
EXT = ROOT / "ext"
BENCH = ROOT / "bench"
COMMIT = "705ccfdf2c9a77d71560c8adcece0663c2f5e18e"  # tag v2.31.1
VERSION = "v2.31.1"
REF = EXT / "bedtools/bin/bedtools"
SCRIPT_FILES = ["prepare.py", "evaluate.py", "gen_data.py"]


def sh(args, **kw):
    print("+", " ".join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), check=True, **kw)


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def tracked_files():
    return sorted(
        SCRIPT_FILES + [str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "data").rglob("*") if p.is_file()]
    )


def deps(prefix):
    """Build zlib v1.3.1 into prefix, once. solver/build.sh uses it as well."""
    prefix = pathlib.Path(prefix).resolve()
    prefix.mkdir(parents=True, exist_ok=True)
    if not (prefix / "lib/libz.a").exists():
        src = prefix / "zlib"
        if not src.exists():
            sh(
                [
                    "git",
                    "clone",
                    "--quiet",
                    "--depth",
                    "1",
                    "--branch",
                    "v1.3.1",
                    "https://github.com/madler/zlib.git",
                    src,
                ]
            )
        # The tag is also checked against the commit it points to.
        actual = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=src, text=True).strip()
        if actual != "51b7f2abdade71cd9bb0e7a373ef2610ec6f9daf":
            raise RuntimeError("Unexpected zlib v1.3.1 revision " + actual)
        sh(["bash", "configure", "--static", "--prefix=" + str(prefix)], cwd=src)
        sh(["make", "-j1"], cwd=src)
        sh(["make", "install"], cwd=src)
    return prefix


def build(src, prefix):
    """Build bedtools with its own Makefile (no autotools needed)."""
    src = pathlib.Path(src).resolve()
    prefix = pathlib.Path(prefix).resolve()
    # The optional bzip2/LZMA CRAM codecs stay off here and in solver/build.sh.
    # BED, gzip, VCF, GFF and BAM are supported; CRAM is not tested.
    config = src / "src/utils/htslib/config.h"
    content = "#define _GNU_SOURCE 1\n#define HAVE_DRAND48 1\n#define HAVE_FSEEKO 1\n#define HAVE_FSYNC 1\n#define HAVE_FTELLO 1\n#define HAVE_GETPAGESIZE 1\n#define HAVE_MMAP 1\n"
    if not config.exists() or config.read_text() != content:
        config.write_text(content)
    env = {**os.environ, "CPATH": str(prefix / "include"), "LIBRARY_PATH": str(prefix / "lib")}
    sh(
        ["make", "-j1", "bin/bedtools", "CXXFLAGS=-O2 -g0", "CFLAGS=-O2 -g0", "BT_LIBS=-lz -lm -lpthread"],
        cwd=src,
        env=env,
    )
    return src / "bin/bedtools"


def timed(args, out):
    out.unlink(missing_ok=True)  # outside the timer, before every repetition
    with out.open("wb") as f:
        start = time.perf_counter()
        r = subprocess.run(
            [str(REF), "coverage", *args],
            stdout=f,
            stderr=subprocess.PIPE,
            timeout=300,
            env={**os.environ, "OMP_NUM_THREADS": "1", "LC_ALL": "C"},
        )
        elapsed = time.perf_counter() - start
    if r.returncode:
        raise RuntimeError(r.stderr.decode(errors="replace"))
    return elapsed, sha(out), out.stat().st_size


def prepare_sets(specs, kind):
    rows = []
    for name, spec in specs.items():
        paths = gen_data.write_dataset(ROOT, name, spec, BENCH / "data")
        args = ["-a", str(ROOT / paths["a"]), "-b", str(ROOT / paths["b"]), *spec["args"]]
        times = []
        out = BENCH / "reference_stdout.tmp"
        for _ in range(3):
            elapsed, h, size = timed(args, out)
            times.append(elapsed)
            if elapsed >= 5:
                break
        row = dict(
            name=name,
            kind=kind,
            real=spec["real"],
            paths=paths,
            args=spec["args"],
            expected_sha256=h,
            expected_bytes=size,
            expected_stdout_sha256=h,
            expected_stdout_bytes=size,
            ref_j1_s=min(times),
            ref_repetitions_s=times,
            input_sha256={k: sha(ROOT / p) for k, p in paths.items()},
        )
        # All inputs are already sorted, so -sorted needs no sorting step.
        sort_args = args if "-sorted" in args else [*args, "-sorted"]
        ts, hs, ss = timed(sort_args, out)
        row.update(ref_sorted_s=ts, ref_sorted_matches=(h == hs and size == ss))
        row["ref_best_s"] = min(row["ref_j1_s"], ts) if row["ref_sorted_matches"] else row["ref_j1_s"]
        out.unlink(missing_ok=True)
        rows.append(row)
        print(json.dumps(row), flush=True)
    return rows


def main():
    os.chdir(ROOT)
    EXT.mkdir(exist_ok=True)
    BENCH.mkdir(exist_ok=True)
    manifest_path = BENCH / "manifest.json"
    if manifest_path.exists():
        old = json.loads(manifest_path.read_text())
        bad = [p for p, h in old["scripts_sha256"].items() if not (ROOT / p).exists() or sha(ROOT / p) != h]
        if bad:
            raise RuntimeError("Scripts or data modified since prepare.py: " + str(bad))
    if not (EXT / "bedtools").exists():
        sh(["git", "clone", "--quiet", "https://github.com/arq5x/bedtools2.git", EXT / "bedtools"])
    sh(["git", "checkout", "--quiet", COMMIT], cwd=EXT / "bedtools")
    if subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=EXT / "bedtools", text=True).strip() != COMMIT:
        raise RuntimeError("Wrong reference commit")
    build(EXT / "bedtools", deps(EXT / "deps"))
    version = subprocess.check_output([str(REF), "--version"], text=True).strip()
    assert VERSION in version, version
    if not manifest_path.exists():
        dev = prepare_sets(gen_data.DEV_SPECS, "dev")
        hold = prepare_sets(gen_data.HOLDOUT_SPECS, "holdout")
        cpu = next(
            (
                l.split(":", 1)[1].strip()
                for l in pathlib.Path("/proc/cpuinfo").read_text().splitlines()
                if l.startswith("model name")
            ),
            "unknown",
        )
        manifest = dict(
            created=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            reference=dict(tool="bedtools coverage", version=VERSION, commit=COMMIT, sha256=sha(REF)),
            threads=os.cpu_count() or 1,
            cpu=cpu,
            python=platform.python_version(),
            compiler=subprocess.check_output(["g++", "--version"], text=True).splitlines()[0],
            dev=dev,
            holdout=hold,
            scripts_sha256={p: sha(ROOT / p) for p in tracked_files()},
        )
        manifest_path.write_text(json.dumps(manifest, indent=2))
        print(f"wrote {manifest_path}")
    print("prepare: done", flush=True)


if __name__ == "__main__":
    main()
